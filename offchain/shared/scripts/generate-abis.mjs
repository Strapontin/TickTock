// Writes src/abis.ts from Foundry's build output, so the off-chain code always matches the contracts.
// Run `forge build` at the repository root first.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "../../../out");

const contracts = [
  ["tickTockFactoryAbi", "TickTockFactory.sol/TickTockFactory.json"],
  ["tickTockHookAbi", "TickTockHook.sol/TickTockHook.json"],
  ["poolManagerAbi", "IPoolManager.sol/IPoolManager.json"],
  ["testTokenAbi", "TestToken.sol/TestToken.json"],
];

let source = "// Generated by scripts/generate-abis.mjs from Foundry's out/. Do not edit.\n";
for (const [name, path] of contracts) {
  const { abi } = JSON.parse(readFileSync(join(out, path), "utf8"));
  source += `\nexport const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`;
}
writeFileSync(join(here, "../src/abis.ts"), source);
console.log(`wrote ${contracts.length} ABIs to shared/src/abis.ts`);
